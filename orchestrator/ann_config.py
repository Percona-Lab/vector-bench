"""The rendered ann-benchmarks config: where it is written, and what it asks for.

`ann_pass.render_config` produces the body; this module persists it and reads
it back to answer one question — how many result files should this phase
write? Split out of `ann_pass` because nothing here needs docker, the engine
registry or the resolved resources: these are functions of plain dicts, which
is what makes them testable without a container and worth keeping apart from
the 250-line phase runner that calls them.

WHY THE COUNT IS NOT ARITHMETIC. ann-benchmarks writes one result file per
(definition, query argument group), and `results.build_result_filepath` names
it from `definition.arguments + query_arguments` ONLY:

    data = definition.arguments + query_arguments
    d.append(re.sub(r"\\W+", "_", json.dumps(data, sort_keys=True)).strip("_")
             + ".hdf5")

The run group's name is not in that path. Two definitions whose argument
values are equal therefore write the SAME file, and multiplying grid sizes
over-counts — `M: [16, 16]` is two definitions and one file, `ef_search:
[10, "10"]` is two query groups and one file because `\\W+` collapses the
quotes. An over-count makes a *healthy* phase fail the shortfall check in
`ann_pass.run_engine` and blames a dead worker for it, which is a worse
failure than the one that check exists to catch.

So the expansion is reproduced from the vendored upstream rather than
approximated, and the answer is the size of the SET of file names. The
reproduced functions name their originals; `work/ann-benchmarks` is generated
and gitignored, so nothing here can import them and the tests cannot read
them.

WHAT THE TESTS PIN, precisely, because the first version of this sentence
overclaimed. `result_stem` has two halves and they are not equally
checkable:

* `json.dumps(..., sort_keys=True)` IS pinned, and the flag is load-bearing:
  `render_config` builds its pgvector arg dict as
  `{M, efConstruction, build_mode}` and `_expand` preserves that order, so an
  unsorted dump names the file
  `euclidean_M_16_efConstruction_200_build_mode_post_10` where the one on disk
  is `euclidean_M_16_build_mode_post_efConstruction_200_10`. One literal in
  the tests is deliberately written in the build order so that deleting the
  flag fails; the others happen to be alphabetical and cannot see it.
* `re.sub(r"\\W+", "_", ...)` is unfalsifiable rather than unpinned, which is a
  weaker claim and the honest one. `json.dumps` defaults to
  `ensure_ascii=True`, so `\\W` never meets a non-ASCII character however odd
  the argument values are.

Six of the pinned names are ones a real ann-benchmarks run left in
`results/annb/` on this machine, which is the only external ground truth
available for either half.
"""

from __future__ import annotations

import itertools
import json
import os
import re
from typing import Any, Dict, List, Set, Tuple

import yaml


def config_path(work_dir: str, engine: str) -> str:
    """Where the rendered ann-benchmarks config for one engine lives.

    Shared by the writer and the reader, so the grid a sweep is checked
    against is the file the container actually consumed.
    """
    return os.path.join(work_dir, "ann_benchmarks", "algorithms", engine,
                        "config.yml")


def write_config(work_dir: str, engine: str, body: Dict[str, Any]) -> str:
    """Write the rendered config into the disposable ann-benchmarks working copy."""
    path = config_path(work_dir, engine)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    header = (
        f"# GENERATED by vector-bench for engine '{engine}'. Do not edit.\n"
        f"# Regenerate with: ./run-benchmark.sh render --profile <name>\n"
    )
    with open(path, "w") as fh:
        fh.write(header)
        yaml.safe_dump(body, fh, sort_keys=False, default_flow_style=False)
    return path


# ---------------------------------------------------------------------------
# How many result files the config asks for
# ---------------------------------------------------------------------------

def result_stem(data: List[Any]) -> str:
    """The result file's name without `.hdf5`, as ann-benchmarks builds it.

    `results.build_result_filepath`, which is handed
    `definition.arguments + query_arguments` and nothing else.

    This one line is the only part of the reproduction that cannot be checked
    by reasoning about the upstream source, because it has to agree with
    Python's `json.dumps` key order and `re` character classes exactly. It is
    pinned in the tests against file names an actual run wrote to disk.
    """
    return re.sub(r"\W+", "_", json.dumps(data, sort_keys=True)).strip("_")


def _expand(args: Any) -> List[Any]:
    """`definitions._generate_combinations`, reproduced.

    A list becomes the cartesian product of its elements, with a scalar
    treated as a one-element list. A dict becomes the cartesian product over
    its list-valued keys, with scalars fixed -- so `{"M": [8, 16, 32],
    "efConstruction": [200], "engine": "InnoDB"}` is three dicts, not nine and
    not one. Counting the scalar `engine` as an axis would inflate the
    expectation and fail every complete phase.
    """
    if isinstance(args, list):
        args = [el if isinstance(el, list) else [el] for el in args]
        return [list(x) for x in itertools.product(*args)]
    if isinstance(args, dict):
        flat = []
        for key, value in args.items():
            if isinstance(value, list):
                flat.append([(key, el) for el in value])
            else:
                flat.append([(key, value)])
        return [dict(x) for x in itertools.product(*flat)]
    raise TypeError(f"no args handling exists for {type(args).__name__}")


def _combinations(run_group: Dict[str, Any], grouped: str, plain: str) -> List[Any]:
    """`definitions.generate_arg_combinations`, reproduced.

    THE ENTRIES OF `arg_groups` ARE MULTIPLIED, NOT ADDED. Upstream expands
    each entry and then takes the cartesian product of the expansions
    (`groups.append(...)` per entry, then `_generate_combinations(groups)`), so
    two entries expanding to 3 and 2 are 6 definitions. Summing them to 5 was
    this helper's first shape and it was wrong about upstream; it is not
    reachable from today's `render_config`, every branch of which emits exactly
    one entry, but a branch that emitted two would have been mis-counted.
    """
    if grouped in run_group:
        groups: List[Any] = []
        for entry in run_group[grouped]:
            groups.append(_expand(entry) if isinstance(entry, dict) else entry)
        return _expand(groups)
    if plain in run_group:
        return _expand(run_group[plain])
    return []


def result_stems(body: Dict[str, Any]) -> Set[Tuple[str, str]]:
    """Every (algorithm, file name) this config will produce.

    A set, because that is what the filesystem holds: see the module
    docstring. Keyed by algorithm as well as stem because upstream writes
    under `results/<dataset>/<count>/<algorithm>/`, so equal stems under two
    algorithms are two files -- today's bodies carry exactly one algorithm,
    but merging them would under-count, and under-counting is the direction
    that hides a lost curve.

    TWO UPSTREAM RULES REPRODUCED HERE THAT NOTHING TODAY EXERCISES, for the
    same reason the `arg_groups` product is: each would over-count, and an
    over-count fails a healthy phase after hours and blames a worker that
    never died.

    * A `disabled` algorithm writes nothing. `main.filter_disabled_algorithms`
      drops it, so it must not be counted. `render_config` always emits
      `disabled: False`.
    * Two entries sharing a `name` are ONE algorithm, not two.
      `_get_algorithm_definitions` does `definitions[cc.pop("name")] = cc`, so
      the later entry replaces the earlier one entirely rather than merging
      with it -- hence the dict below, keyed by name, which keeps the last.

    `@metric`, `@count` and `@dimension` are left unsubstituted. Upstream
    replaces them from the dataset and the run, and all three are constant
    across every definition in one phase, so they cannot change the size of
    this set for any body `render_config` emits. (Not in general: a grid that
    swept the literal `"@metric"` beside the value it resolves to would see
    upstream collapse the two and this count them separately. Nothing emits
    that, and resolving it here would mean knowing the dataset's metric, which
    this module is deliberately not given.)
    """
    return {(name, result_stem(index_args + query))
            for name, index_args, query in result_definitions(body)}


def result_definitions(body: Dict[str, Any]
                       ) -> List[Tuple[str, List[Any], List[Any]]]:
    """(algorithm, index arguments, query arguments) per file the body asks
    for, before the stem collapses them -- the expansion `result_stems`
    counts. Split out so `ann_provenance` can tell which build parameters a
    result file was written for, which the stem alone spells only lossily.
    """
    out: List[Tuple[str, List[Any], List[Any]]] = []
    by_name: Dict[str, Dict[str, Any]] = {}
    for algorithm in ((body.get("float") or {}).get("any") or []):
        by_name[str(algorithm.get("name", ""))] = algorithm
    for name, algorithm in by_name.items():
        if algorithm.get("disabled"):
            continue
        base_args = list(algorithm.get("base_args") or [])
        for run_group in (algorithm.get("run_groups") or {}).values():
            if "arg_groups" not in run_group and "args" not in run_group:
                # `prepare_args` raises on this, so the run would not start.
                raise ValueError(f"unknown run_group structure: {run_group}")
            index_args = _combinations(run_group, "arg_groups", "args")
            # `definition.query_argument_groups or [[]]` -- a definition with
            # no query args still runs once, and still writes one file.
            query_args = _combinations(run_group, "query_arg_groups",
                                       "query_args") or [[]]
            for arg_group in index_args:
                arguments = list(base_args)
                if isinstance(arg_group, list):
                    arguments.extend(arg_group)
                else:
                    arguments.append(arg_group)
                for query in query_args:
                    out.append((name, arguments, list(query)))
    return out


def expected_result_count(body: Dict[str, Any]) -> int:
    """How many result files a rendered config asks ann-benchmarks to write.

    The rendered config is the only place that says -- the grid comes from the
    profile, the resource pass and `render_config`'s per-engine branch, and no
    record of it reaches the result tree -- so without this, `after` can only
    be compared against `before`, which cannot tell a finished sweep from an
    interrupted one. See `ann_pass.run_engine`.

    Returns 0 for a body it cannot read, which switches that check off rather
    than guessing: 0 can never be a shortfall, and a wrong non-zero number
    would fail a healthy phase.
    """
    try:
        return len(result_stems(body))
    except (AttributeError, KeyError, TypeError, ValueError):
        return 0


def expected_results(work_dir: str, engine: str) -> int:
    """`expected_result_count` for the config rendered into the working copy.

    Read back from disk rather than passed in: the body is rendered by the
    caller that writes it and `run_engine` is handed only the profile, and a
    render that failed to land must not be checked against a grid that
    existed only in memory.
    """
    body = read_config(work_dir, engine)
    return 0 if body is None else expected_result_count(body)


def read_config(work_dir: str, engine: str) -> Any:
    """The rendered config as the container consumed it, or None."""
    try:
        with open(config_path(work_dir, engine)) as fh:
            return yaml.safe_load(fh)
    except (OSError, yaml.YAMLError):
        return None
